#!/usr/bin/env node
/**
 * Downloads the web fonts from Google Fonts and self-hosts them.
 *   node tools/fetch-fonts.mjs
 *
 * Why self-host instead of linking to fonts.googleapis.com:
 *   - the browser blocks script execution on a pending stylesheet, so a slow
 *     third-party CSS request delays the contact form's JavaScript;
 *   - one less external origin means a stricter CSP and no third-party request
 *     carrying your visitors' IP addresses (relevant under the DPDP Act);
 *   - fewer DNS + TLS round trips on the mobile networks most of our visitors use.
 *
 * Both families are licensed under the SIL Open Font License 1.1, which permits
 * redistribution — see src/assets/fonts/OFL.txt.
 *
 * Re-run this only if you change the font families in src/assets/css/style.css.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(ROOT, 'src', 'assets', 'fonts');
const OUT_CSS = path.join(ROOT, 'src', 'assets', 'css', 'fonts.css');

// A desktop UA makes Google serve woff2 (the modern, smallest format).
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const CSS_URL =
  'https://fonts.googleapis.com/css2' +
  '?family=Fraunces:opsz,wght@9..144,600' +
  '&family=Plus+Jakarta+Sans:wght@400;500;600;700' +
  '&display=swap';

// Only these subsets ship. Latin + latin-ext covers English and the Latin
// transliteration of Hindi ("Samajh nahi aa raha") used across the site.
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

async function main() {
  await fs.mkdir(FONT_DIR, { recursive: true });

  const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();

  // Google's CSS is a sequence of "/* subset */ @font-face { ... }" blocks.
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
  if (!blocks.length) throw new Error('Could not parse the Google Fonts CSS response.');

  const out = [
    '/* Self-hosted web fonts — generated by tools/fetch-fonts.mjs. Do not edit by hand.',
    '   Fraunces and Plus Jakarta Sans, SIL Open Font License 1.1. */',
    '',
  ];
  let kept = 0;

  for (const [, subset, block] of blocks) {
    if (!KEEP_SUBSETS.has(subset)) continue;

    const url = block.match(/src:\s*url\((https:[^)]+)\)/)?.[1];
    const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = block.match(/font-weight:\s*([\d ]+)/)?.[1]?.trim();
    if (!url || !family) continue;

    const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight.replace(/\s+/g, '-')}-${subset}.woff2`;
    const bytes = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
    await fs.writeFile(path.join(FONT_DIR, file), bytes);
    console.log(`  ↓ ${file} (${(bytes.length / 1024).toFixed(1)} KB)`);

    out.push(`/* ${subset} */`, block.replace(/url\(https:[^)]+\)/, `url(../fonts/${file})`), '');
    kept++;
  }

  await fs.writeFile(OUT_CSS, out.join('\n'));
  console.log(`\n✅ ${kept} font files self-hosted, CSS written to src/assets/css/fonts.css\n`);
}

main().catch((err) => {
  console.error(`\n❌ Font download failed: ${err.message}`);
  console.error('   The site still works — it falls back to Georgia and system sans.\n');
  process.exit(1);
});
